/// `c_pow` must land on the requested side of the exact value to within one unit (1e-18), and its
/// error must be small both absolutely (series precision) and relative to the deviation of the
/// result from 1.0 (so a doubled or zeroed first-order term is caught even when it is tiny).
#[test]
fn test_c_pow_bounds_against_exact() {
    let env = Env::default();
    let one = crate::c_consts::BONE;
    let precision = crate::c_consts::CPOW_PRECISION;

    for (base, exp, exact_floor, exact_ceil) in C_POW_GRID {
        env.cost_estimate().budget().reset_unlimited();
        let b = I256::from_i128(&env, *base);
        let e = I256::from_i128(&env, *exp);
        let up = c_pow(&env, &b, &e, true).to_i128().unwrap();
        let down = c_pow(&env, &b, &e, false).to_i128().unwrap();

        // direction, within one unit
        assert!(
            up >= *exact_floor,
            "c_pow({base}, {exp}, true) = {up} is below floor(exact) = {exact_floor}"
        );
        assert!(
            down <= *exact_ceil,
            "c_pow({base}, {exp}, false) = {down} is above ceil(exact) = {exact_ceil}"
        );

        // magnitude: never more than twice the series precision from exact ...
        let err_up = up - exact_ceil;
        let err_down = exact_floor - down;
        assert!(
            err_up <= 2 * precision,
            "c_pow({base}, {exp}, true) overshoots by {err_up}"
        );
        assert!(
            err_down <= 2 * precision,
            "c_pow({base}, {exp}, false) undershoots by {err_down}"
        );

        // ... and never more than half the deviation from 1.0, plus ten units. The ten units
        // cover the directed rounding of each multiply in `c_powi` (at most 2*log2(exp) of them)
        // when the base is within a few units of 1.0 and every ceil absorbs the whole deviation.
        let deviation = (*exact_floor - one).abs();
        assert!(
            err_up <= deviation / 2 + 10,
            "c_pow({base}, {exp}, true) error {err_up} exceeds half the deviation {deviation}"
        );
        assert!(
            err_down <= deviation / 2 + 10,
            "c_pow({base}, {exp}, false) error {err_down} exceeds half the deviation {deviation}"
        );
    }
}
